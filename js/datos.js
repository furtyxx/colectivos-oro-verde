function armar(id, linea, tipo, nombre, vigencia, cols, texto) {
  const [ida, vuelta] = cols.split('||').map(x => x.split('|'));
  return {
    id, linea, tipo, nombre, vigencia, fuente: 'precargada', ver: VERSION_DATOS,
    nombres: [...ida, ...vuelta], vueltaDesde: ida.length,
    filas: texto.trim().split('\n').map(r => filaAMin(r.trim().split(/\s+/).map(c => (c === '-' ? null : c)))),
  };
}

